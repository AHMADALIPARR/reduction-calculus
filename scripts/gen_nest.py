#!/usr/bin/env python3
"""Generate ReductionCalculus/Nest.lean.

The `Nest k` family uses a fixed 37-name alphabet for its proposition
variables: P, Q, ..., Z (11 single letters), then AA, BB, ..., ZZ (26
doubled letters).  `Nest k` has `k` propositions and `k - 1` implications
`h1 .. h(k-1)`, and concludes with the closed lift.

Every theorem is proved by the same route:

    have hchain : Reduces ImpStep <first> <last> :=
      Reduces.step h1 <| ... <| Reduces.refl <last>
    exact (nest A B φ hchain hp i a).2

so the generated statements are instances of the single schema `nest`
from `ReductionCalculus.Semantics`.

Usage:  python3 scripts/gen_nest.py > ReductionCalculus/Nest.lean
"""



SINGLES = list("PQRSTUVWXYZ")
DOUBLES = [c * 2 for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ"]
NAMES = SINGLES + DOUBLES  # 37 names: P .. Z, AA .. ZZ

FIRST_K, LAST_K = 19, 37
WIDTH = 100


def wrap_binder(first_prefix: str, cont_prefix: str, items: list[str], suffix: str) -> str:
    """Greedily pack whole `items` onto lines of at most WIDTH columns.

    Items are never split: a binder such as `(h8 : W → X)` stays intact, so
    the generated Lean always parses.
    """
    lines: list[str] = []
    cur = first_prefix
    for item in items:
        sep = "" if cur == first_prefix else " "
        candidate = cur + sep + item
        if len(candidate) > WIDTH and cur != first_prefix:
            lines.append(cur)
            cur = cont_prefix + item
        else:
            cur = candidate
    lines.append(cur + suffix)
    return "\n".join(lines)


def theorem(k: int) -> str:
    names = NAMES[:k]
    steps = k - 1

    lines = []
    lines.append(f"/-- `Nest{k}`: a chain of {k} propositions with {steps} implications,")
    lines.append("concluding with the closed lift. Instance of `nest`. -/")
    lines.append(f"theorem Nest{k} {{ι : Type _}} (A B : ι → Type _) (φ : ∀ i, A i → B i)")
    lines.append(wrap_binder("    (", "     ", names, " : Prop)"))
    hyps = [f"(h{i + 1} : {names[i]} → {names[i + 1]})" for i in range(steps)]
    hyps.append(f"(hp : {names[0]})")
    hyps.append("(i : ι)")
    hyps.append("(a : A i)")
    lines.append(wrap_binder("    ", "    ", hyps, " :"))
    lines.append("    ∃ b : B i, b = φ i a := by")
    lines.append(f"  have hchain : Reduces ImpStep {names[0]} {names[-1]} :=")
    for i in range(steps):
        lines.append(f"    Reduces.step h{i + 1} <|")
    lines.append(f"    Reduces.refl {names[-1]}")
    lines.append("  exact (nest A B φ hchain hp i a).2")
    return "\n".join(lines)


HEADER = '''/-
# Reduction Calculus — the `Nest` family

`Nest19` … `Nest37`: chains of implications of increasing length, each
concluding with the closed lift of `a : A i` along `φ`.

This file is generated by `scripts/gen_nest.py`. Do not edit it by hand;
change the generator and re-run it.

Every theorem is an instance of the schema `nest`:

* the chain `Reduces ImpStep <first> <last>` is built from `h1 … h(k-1)`;
* `nest` turns that chain plus `hp : P` into the reduced proposition *and*
  the closed lift;
* the theorem statement only asks for the lift, so we take `.2`.

The proposition names follow a fixed 37-letter alphabet
(`P … Z`, then `AA … ZZ`), which is exactly the alphabet used by the
source proofs.
-/

import ReductionCalculus.Semantics

namespace ReductionCalculus

'''

FOOTER = "\n\nend ReductionCalculus\n"


def main() -> None:
    body = "\n\n".join(theorem(k) for k in range(FIRST_K, LAST_K + 1))
    print(HEADER + body + FOOTER, end="")


if __name__ == "__main__":
    main()
